# Mirrors LogicProMCP's AXValueExtractors.logicMixerFaderPositionToContract.
CONTRACT_AT_POSITION = (
    (0.0, 0.0),
    (0.1072961373390558, 0.2),
    (70.0 / 233.0, 0.4),
    (0.4206008583690987, 0.5),
    (0.48497854077253216, 0.6),
    (0.8111587982832618, 0.8),
    (1.0, 1.0),
)

RAW_MAX = len(DB_AT_RAW) - 1
PAN_CENTRE_RAW = 64
PAN_HALF_RANGE = 63.5


def raw_nearest(db: float) -> int:
    return min(range(len(DB_AT_RAW)), key=lambda raw: abs(DB_AT_RAW[raw] - db))


def volume_contract(raw: int) -> float:
    position = raw / RAW_MAX
    for (p0, c0), (p1, c1) in zip(CONTRACT_AT_POSITION, CONTRACT_AT_POSITION[1:]):
        if position <= p1:
            return c0 + (position - p0) / (p1 - p0) * (c1 - c0)
    return 1.0


def pan_contract(pan: int) -> float:
    return max(-1.0, min(1.0, (pan + PAN_CENTRE_RAW - PAN_HALF_RANGE) / PAN_HALF_RANGE))
